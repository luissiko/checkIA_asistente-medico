import {existsSync} from 'node:fs';
import {initializeApp,applicationDefault} from 'firebase-admin/app';
import {getAuth} from 'firebase-admin/auth';
import {getFirestore} from 'firebase-admin/firestore';
import {runtimeConfig} from '../src/runtime-config.js';
import {AdminService} from '../src/admin.js';
import {createOpenAIClient} from '../src/openai-client.js';
import {createEmbeddingClient} from '../src/embeddings.js';
import {loadRag} from '../src/rag.js';
import {IntegratedStore} from './integrated-store.mjs';
import {IntegratedOrientationService} from './integrated-orientation.mjs';
import {createPaso23Client} from './local-client.mjs';
import {createIntegratedApp} from './integrated-app.mjs';
const env=new URL('../.env',import.meta.url);
if(!process.env.K_SERVICE&&existsSync(env))process.loadEnvFile(env);
const runtime=runtimeConfig();
if(process.env.FIREBASE_AUTH_EMULATOR_HOST||process.env.FIRESTORE_EMULATOR_HOST)throw new Error('Retira las variables de emulador de esta configuración.');
const firebase=initializeApp({projectId:'checkia-project',credential:applicationDefault()});
const store=new IntegratedStore(getFirestore(firebase));
const client=createPaso23Client({timeoutMs:runtime.llmTimeoutMs});
const retriever=loadRag(createEmbeddingClient({enabled:client.configured,timeoutMs:runtime.embeddingTimeoutMs}));
if(runtime.cloud&&(!retriever.status.ready||!client.configured))throw new Error('Prepara el índice RAG, la vigencia de fuentes y la configuración del proveedor antes de publicar.');
const orientationService=new IntegratedOrientationService(store,client,{retriever,legacyClient:createOpenAIClient({timeoutMs:runtime.llmTimeoutMs})});
const app=createIntegratedApp({store,orientationService,adminService:new AdminService(store.db),verifyToken:token=>getAuth(firebase).verifyIdToken(token,true)});
const server=app.listen(runtime.port,runtime.host,()=>console.log('CHECKIA Paso 23 · '+runtime.host+':'+runtime.port));
server.on('error',()=>{console.error('No se pudo iniciar CHECKIA. Revisa el puerto y la configuración del servicio.');process.exitCode=1;});