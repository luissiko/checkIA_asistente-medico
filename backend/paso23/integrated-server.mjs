import {existsSync} from 'node:fs';
import {initializeApp,applicationDefault} from 'firebase-admin/app';
import {getAuth} from 'firebase-admin/auth';
import {getFirestore} from 'firebase-admin/firestore';
import {AdminService} from '../src/admin.js';
import {createOpenAIClient} from '../src/openai-client.js';
import {createEmbeddingClient} from '../src/embeddings.js';
import {loadRag} from '../src/rag.js';
import {IntegratedStore} from './integrated-store.mjs';
import {IntegratedOrientationService} from './integrated-orientation.mjs';
import {createPaso23Client} from './local-client.mjs';
import {createIntegratedApp} from './integrated-app.mjs';
const env=new URL('../.env',import.meta.url);if(existsSync(env))process.loadEnvFile(env);
if(process.env.K_SERVICE)throw new Error('Este arranque del Paso 23 solo permite pruebas locales.');
if(process.env.FIREBASE_AUTH_EMULATOR_HOST||process.env.FIRESTORE_EMULATOR_HOST)throw new Error('Usa la configuración local habitual de Firebase del proyecto.');
const firebase=initializeApp({projectId:'checkia-project',credential:applicationDefault()});
const store=new IntegratedStore(getFirestore(firebase));
const client=createPaso23Client(),retriever=loadRag(createEmbeddingClient({enabled:client.configured}));
const orientationService=new IntegratedOrientationService(store,client,{retriever,legacyClient:createOpenAIClient()});
const app=createIntegratedApp({store,orientationService,adminService:new AdminService(store.db),verifyToken:token=>getAuth(firebase).verifyIdToken(token,true)});
const server=app.listen(3001,'127.0.0.1',()=>console.log('CHECKIA · Preguntas Paso 23 integradas · http://127.0.0.1:3001 · Abre la aplicación en http://127.0.0.1:5173'));
server.on('error',e=>{console.error(e.code==='EADDRINUSE'?'El puerto 3001 está ocupado. Cierra el backend anterior antes de iniciar esta prueba.':'No se pudo iniciar CHECKIA local.');process.exitCode=1;});
