import {runtimeConfig} from './runtime-config.js';
import {AdminService} from './admin.js';
import {createEmbeddingClient} from './embeddings.js';
import {loadRag} from './rag.js';
import {existsSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {createOpenAIClient} from './openai-client.js';
import {OrientationService} from './orientation.js';
import { initializeApp, applicationDefault } from 'firebase-admin/app';
import { getAuth } from 'firebase-admin/auth';
import { getFirestore } from 'firebase-admin/firestore';
import { createApp } from './app.js';
import { FirestoreStore } from './firestore-store.js';
const envPath=fileURLToPath(new URL('../.env',import.meta.url));
if(!process.env.K_SERVICE&&existsSync(envPath))process.loadEnvFile(envPath);
const runtime=runtimeConfig();
const projectId = 'checkia-project';
if (process.env.FIREBASE_AUTH_EMULATOR_HOST || process.env.FIRESTORE_EMULATOR_HOST) throw new Error('Esta etapa prueba el proyecto real. Retira las variables de emulador de esta terminal.');
const firebaseApp = initializeApp({ projectId, credential: applicationDefault() });
const verifyToken = token => getAuth(firebaseApp).verifyIdToken(token, true);
const store = new FirestoreStore(getFirestore(firebaseApp));
const {port,host}=runtime;
const client=createOpenAIClient({timeoutMs:runtime.llmTimeoutMs});
const retriever=loadRag(createEmbeddingClient({enabled:client.configured,timeoutMs:runtime.embeddingTimeoutMs}));
if(runtime.cloud&&!retriever.status.ready)throw new Error('Prepara el índice RAG, la vigencia del corpus y la configuración del LLM antes del despliegue.');
const orientationService=new OrientationService(store,client,{retriever});
console.log('Información de apoyo: '+retriever.status.state+'.');
console.log(client.configured?'Orientacion LLM configurada.':'Orientacion LLM desactivada; la entrevista sigue disponible.');
createApp({ store, verifyToken, orientationService,adminService:new AdminService(store.db) }).listen(port, host, () => console.log(`CHECKIA paso 22: http://${host}:${port} · Firebase + Firestore · orientación LLM de prueba`));
